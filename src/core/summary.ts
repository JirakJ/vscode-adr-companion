/**
 * Shareable Markdown: the status summary (clipboard) and the generated
 * `index.md` table of contents for the ADR directory.
 */
import { AdrRecord, formatId } from './parser';
import { AdrStatus, STATUS_ORDER, statusDisplayName } from './status';

export function countByStatus(records: AdrRecord[]): Map<AdrStatus, number> {
  const counts = new Map<AdrStatus, number>();
  for (const r of records) counts.set(r.status, (counts.get(r.status) ?? 0) + 1);
  return counts;
}

export function summaryLine(records: AdrRecord[]): string {
  if (records.length === 0) return 'No Architecture Decision Records found.';
  const counts = countByStatus(records);
  const parts = STATUS_ORDER.filter((s) => counts.get(s)).map((s) => `${counts.get(s)} ${statusDisplayName(s).toLowerCase()}`);
  return `**${records.length} ${records.length === 1 ? 'ADR' : 'ADRs'}** — ${parts.join(', ')}`;
}

export function badge(records: AdrRecord[]): string {
  const counts = countByStatus(records);
  const outdated = (counts.get('deprecated') ?? 0) + (counts.get('superseded') ?? 0);
  const color = outdated === 0 ? 'brightgreen' : 'yellow';
  return `![ADRs](https://img.shields.io/badge/ADRs-${records.length}-${color})`;
}

export function escapeCell(text: string): string {
  return text.replace(/\\/g, '\\\\').replace(/\|/g, '\\|').replace(/\r?\n/g, ' ').trim();
}

function sorted(records: AdrRecord[]): AdrRecord[] {
  return [...records].sort((a, b) => (a.id ?? Infinity) - (b.id ?? Infinity) || a.fileName.localeCompare(b.fileName));
}

function idCell(r: AdrRecord): string {
  return r.id != null ? formatId(r.id) : '—';
}

export function renderSummary(records: AdrRecord[]): string {
  const lines = ['# Architecture Decision Records', '', badge(records), '', summaryLine(records), ''];
  if (records.length === 0) {
    lines.push('_No ADRs to list._');
  } else {
    lines.push('| # | Title | Status | Date |', '|---|-------|--------|------|');
    for (const r of sorted(records)) {
      lines.push(`| ${idCell(r)} | ${escapeCell(r.title)} | ${statusDisplayName(r.status)} | ${r.date ?? '—'} |`);
    }
  }
  return lines.join('\n') + '\n';
}

export type IndexGrouping = 'status' | 'year' | 'none';

export function renderIndex(records: AdrRecord[], grouping: IndexGrouping = 'none', generatedOn?: string): string {
  const lines = [
    '<!-- Generated by ADR Companion ("ADR: Generate Index"). Manual edits are overwritten. -->',
    '',
    '# Architecture Decision Records',
    '',
    summaryLine(records),
    '',
  ];
  if (generatedOn) lines.push(`_Last generated ${generatedOn}._`, '');
  const row = (r: AdrRecord) => {
    const successor = r.supersededBy.length ? r.supersededBy.map((s) => `ADR-${formatId(s)}`).join(', ') : '';
    return `| ${idCell(r)} | [${escapeCell(r.title || r.fileName)}](${encodeURI(r.fileName)}) | ${statusDisplayName(r.status)} | ${r.date ?? '—'} | ${successor} |`;
  };
  const table = (rs: AdrRecord[]) => {
    lines.push('| # | Decision | Status | Date | Superseded by |', '|---|----------|--------|------|---------------|');
    for (const r of sorted(rs)) lines.push(row(r));
    lines.push('');
  };
  if (records.length === 0) {
    lines.push('_No decision records yet._', '');
  } else if (grouping === 'status') {
    for (const s of STATUS_ORDER) {
      const bucket = records.filter((r) => r.status === s);
      if (bucket.length === 0) continue;
      lines.push(`## ${statusDisplayName(s)} (${bucket.length})`, '');
      table(bucket);
    }
  } else if (grouping === 'year') {
    const years = [...new Set(records.map((r) => r.date?.slice(0, 4) ?? 'Undated'))].sort((a, b) =>
      a === 'Undated' ? 1 : b === 'Undated' ? -1 : b.localeCompare(a),
    );
    for (const y of years) {
      const bucket = records.filter((r) => (r.date?.slice(0, 4) ?? 'Undated') === y);
      lines.push(`## ${y} (${bucket.length})`, '');
      table(bucket);
    }
  } else {
    table(records);
  }
  return lines.join('\n').replace(/\n+$/, '') + '\n';
}

/** Records ordered for the timeline view: newest first, undated last. */
export function timeline(records: AdrRecord[]): { period: string; records: AdrRecord[] }[] {
  const groups = new Map<string, AdrRecord[]>();
  for (const r of records) {
    const key = r.date ? r.date.slice(0, 7) : 'Undated';
    const list = groups.get(key) ?? [];
    list.push(r);
    groups.set(key, list);
  }
  return [...groups.entries()]
    .sort(([a], [b]) => (a === 'Undated' ? 1 : b === 'Undated' ? -1 : b.localeCompare(a)))
    .map(([period, rs]) => ({
      period,
      records: rs.sort((a, b) => (b.date ?? '').localeCompare(a.date ?? '') || (b.id ?? 0) - (a.id ?? 0)),
    }));
}

/** GitHub Actions workflow that runs the ADR Companion CLI on pull requests. */
export const CLI_ASSET = 'adr-companion-cli.cjs';
export const REPO = 'JirakJ/vscode-adr-companion';

export function cliDownloadUrl(version: string): string {
  return `https://github.com/${REPO}/releases/download/v${version}/${CLI_ASSET}`;
}

export function ciWorkflow(version: string): string {
  return `# Generated by ADR Companion ("ADR: Create GitHub Actions Workflow").
# Lints the decision log and enforces requireAdrForPaths from .adr-config.yaml.
name: ADR governance

on:
  pull_request:

permissions:
  contents: read

jobs:
  adr:
    runs-on: ubuntu-latest
    steps:
      - uses: actions/checkout@v4
        with:
          fetch-depth: 0
          persist-credentials: false
      - uses: actions/setup-node@v4
        with:
          node-version: 20
      - name: Download ADR Companion CLI ${version}
        run: curl -fsSL -o "$RUNNER_TEMP/adr-companion.cjs" ${cliDownloadUrl(version)}
      - name: Lint decision records
        run: node "$RUNNER_TEMP/adr-companion.cjs" lint --format github
      - name: Require an ADR for architecturally significant changes
        run: node "$RUNNER_TEMP/adr-companion.cjs" governance --format github
`;
}

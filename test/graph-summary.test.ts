import { describe, expect, it } from 'vitest';
import { buildGraph, dotEscape, mermaidEscape, renderDot, renderMermaid } from '../src/core/graph';
import { parseAdr } from '../src/core/parser';
import { badge, renderIndex, renderSummary, summaryLine, timeline } from '../src/core/summary';

const records = [
  parseAdr('# 1. Use MySQL\n\nDate: 2025-01-10\n\n## Status\n\nSuperseded by ADR-0003\n', '/r/0001-use-mysql.md'),
  parseAdr('# 2. Use REST | JSON\n\nDate: 2025-06-01\n\n## Status\n\nAccepted\n\n## Context\n\nRelated to ADR-0001.\n\n## Decision\n\nD\n\n## Consequences\n\nC\n', '/r/0002-use-rest.md'),
  parseAdr('# 3. Use PostgreSQL\n\nDate: 2026-02-03\n\n## Status\n\nAccepted\n\nSupersedes ADR-0001\n\n## Decision\n\nIt depends on ADR-0002.\n', '/r/0003-use-postgresql.md'),
  parseAdr('# 4. "Quoted" <idea>\n\n## Status\n\nProposed\n', '/r/0004-idea.md'),
];

describe('graph', () => {
  it('builds one supersede edge per pair plus text relations', () => {
    const g = buildGraph(records);
    expect(g.nodes.map((n) => n.id)).toEqual([1, 2, 3, 4]);
    expect(g.edges).toEqual([
      { from: 2, to: 1, kind: 'related' },
      { from: 3, to: 1, kind: 'supersedes' },
      { from: 3, to: 2, kind: 'depends-on' },
    ]);
  });

  it('renders deterministic Mermaid', () => {
    const out = renderMermaid(buildGraph(records), { direction: 'LR' });
    expect(out.startsWith('flowchart LR\n')).toBe(true);
    expect(out).toContain('ADR_0003 -- supersedes --> ADR_0001');
    expect(out).toContain('ADR_0002["ADR-0002 Use REST &#124; JSON"]');
    expect(out).toContain('ADR_0004(["ADR-0004 &quot;Quoted&quot; &lt;idea&gt;"])');
    expect(out).toContain('class ADR_0001 superseded');
    expect(renderMermaid(buildGraph(records), { clusterByStatus: true })).toContain('subgraph accepted_group["Accepted"]');
    expect(mermaidEscape('a`b\nc')).toBe('a&#96;b c');
  });

  it('renders DOT', () => {
    const out = renderDot(buildGraph(records), { clusterByStatus: true });
    expect(out).toContain('digraph adr {');
    expect(out).toContain('subgraph cluster_accepted {');
    expect(out).toContain('ADR_0003 -> ADR_0001 [label="supersedes"];');
    expect(out).toContain('label="ADR-0004\\n\\"Quoted\\" <idea>"');
    expect(dotEscape('a\\b')).toBe('a\\\\b');
  });
});

describe('summary', () => {
  it('summarises statuses with a badge', () => {
    expect(summaryLine(records)).toBe('**4 ADRs** — 1 proposed, 2 accepted, 1 superseded');
    expect(badge(records)).toContain('ADRs-4-yellow');
    expect(badge(records.slice(1, 2))).toContain('brightgreen');
    expect(summaryLine([])).toBe('No Architecture Decision Records found.');
    const md = renderSummary(records);
    expect(md).toContain('| 0002 | Use REST \\| JSON | Accepted | 2025-06-01 |');
    expect(renderSummary([])).toContain('_No ADRs to list._');
  });

  it('generates an index in three layouts', () => {
    const flat = renderIndex(records, 'none', '2026-06-01');
    expect(flat).toContain('Generated by ADR Companion');
    expect(flat).toContain('| 0001 | [Use MySQL](0001-use-mysql.md) | Superseded | 2025-01-10 | ADR-0003 |');
    expect(renderIndex(records, 'status')).toContain('## Accepted (2)');
    const byYear = renderIndex(records, 'year');
    expect(byYear.indexOf('## 2026')).toBeLessThan(byYear.indexOf('## 2025'));
    expect(byYear).toContain('## Undated (1)');
    expect(renderIndex([], 'none')).toContain('_No decision records yet._');
  });

  it('builds a newest-first timeline', () => {
    expect(timeline(records).map((g) => g.period)).toEqual(['2026-02', '2025-06', '2025-01', 'Undated']);
  });
});
